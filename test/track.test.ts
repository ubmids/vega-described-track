import {atDensity, parseTimestamp, parseTrack, parseWebVTT} from '../src/track';

const VTT = `WEBVTT

NOTE Audio description generated by Aloud.

1 audio=cue-001.m4a gap=100.0-106.4
00:01:41.530 --> 00:01:45.980 align:start
A grey-haired man lies on a bench while a soldier aims a rifle.

2
01:48.530 --> 01:53.520
Through a circular viewport, a <i>large</i> airship
hovers above a city.
`;

describe('WebVTT', () => {
  test('reads times, text, audio and the gap', () => {
    const t = parseWebVTT(VTT);
    expect(t.cues).toHaveLength(2);
    expect(t.cues[0]).toEqual({
      start: 101.53, end: 105.98,
      text: 'A grey-haired man lies on a bench while a soldier aims a rifle.',
      audio: 'cue-001.m4a', gap: [100.0, 106.4],
    });
  });

  test('joins lines, strips tags, and accepts short timestamps', () => {
    const c = parseWebVTT(VTT).cues[1];
    expect(c.start).toBeCloseTo(108.53);
    expect(c.text).toBe('Through a circular viewport, a large airship hovers above a city.');
    expect(c.gap).toBeNull();
  });

  test('names the audio for cues that do not, in file order', () => {
    const t = parseWebVTT(VTT, {
      audioFor: (_c, i) => `/pkg/assets/ad/cue-${String(i + 1).padStart(3, '0')}.m4a`,
    });
    expect(t.cues.map((c) => c.audio)).toEqual(['cue-001.m4a', '/pkg/assets/ad/cue-002.m4a']);
  });

  test('is not WebVTT without its header, and drops broken cues rather than throwing', () => {
    expect(parseWebVTT('1\n00:00:01.000 --> 00:00:02.000\nHi').cues).toEqual([]);
    const t = parseWebVTT('WEBVTT\n\n00:00:05.000 --> 00:00:04.000\nBackwards\n\n' +
                          'nonsense --> 00:00:09.000\nBad\n\n' +
                          '00:00:07.000 --> 00:00:08.000\n');
    expect(t.cues.map((c) => c.text)).toEqual([]);
    const ok = parseWebVTT('\uFEFFWEBVTT\r\n\r\n00:00:10.000 --> 00:00:11.000\r\nKept\r\n');
    expect(ok.cues.map((c) => c.text)).toEqual(['Kept']);
  });

  test('timestamps', () => {
    expect(parseTimestamp('00:01:41.530')).toBeCloseTo(101.53);
    expect(parseTimestamp('1:41.5')).toBeCloseTo(101.5);
    expect(parseTimestamp('01:00:00,250')).toBeCloseTo(3600.25);
    expect(parseTimestamp('soon')).toBeNaN();
  });
});

describe('JSON', () => {
  test('keeps good cues in order, drops broken ones, never throws', () => {
    const t = parseTrack({source: 'film.mp4', cues: [
      {start: 9, end: 10, text: 'Second.', gap: [8, 12]},
      {start: 1, end: 2, text: ' First. ', audio: 'cue-001.m4a'},
      {start: 3, end: 2, text: 'Backwards.'},
      {start: 4, end: 5, text: '   '},
      null,
    ]});
    expect(t.cues.map((c) => c.text)).toEqual(['First.', 'Second.']);
    expect(t.cues[1].gap).toEqual([8, 12]);
    expect(parseTrack('garbage').cues).toEqual([]);
  });
});

test('sparse keeps the half of the cues with the most room, in film order', () => {
  const cues = [1, 4, 2, 3].map((len, i) => ({start: i * 10, end: i * 10 + len, text: `${i}`}));
  expect(atDensity({source: '', cues}, 'sparse').map((c) => c.text)).toEqual(['1', '3']);
  expect(atDensity({source: '', cues}, 'full')).toHaveLength(4);
});
